// Seeds a public SAMPLE Sponsored Research Brief for a real, well-known ticker
// (default $MSFT) so site visitors can see what the paid product produces.
//
// Run: node scripts/seed-sample-brief.mjs [TICKER]
// Needs: NEXT_PUBLIC_SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY, ANTHROPIC_API_KEY
//
// Idempotent: removes any existing sample brief for the ticker, then inserts a
// fresh one with published=true, is_sample=true, company_id=null.

import { createClient } from "@supabase/supabase-js";
import fs from "fs";

// Load .env.local ourselves so this works regardless of how the shell sources env.
try {
  for (const line of fs.readFileSync(".env.local", "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)$/);
    if (m && process.env[m[1]] === undefined) process.env[m[1]] = m[2].replace(/^['"]|['"]$/g, "");
  }
} catch { /* env may already be in the environment */ }

const TICKER = (process.argv[2] || "MSFT").toUpperCase();
const URL = process.env.NEXT_PUBLIC_SUPABASE_URL;
const SERVICE_KEY = process.env.SUPABASE_SERVICE_ROLE_KEY;
const ANTHROPIC_KEY = process.env.ANTHROPIC_API_KEY;
const MODEL = "claude-sonnet-4-6";

if (!URL || !SERVICE_KEY) {
  console.error("Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY");
  process.exit(1);
}

// Well-known public facts about the company (a real customer brief is generated
// from a live audit; for a sample we hand the model accurate public context).
const COMPANIES = {
  MSFT: {
    name: "Microsoft Corporation",
    ticker: "MSFT",
    exchange: "NASDAQ",
    sector: "Technology — Software & Cloud",
    facts:
      "Microsoft Corporation ($MSFT), NASDAQ-listed, HQ Redmond, Washington. " +
      "Operates in three reportable segments: Productivity and Business Processes (Microsoft 365, Office, LinkedIn, Dynamics), " +
      "Intelligent Cloud (Azure, server products, enterprise services), and More Personal Computing (Windows, devices, gaming/Xbox, search). " +
      "Files annual 10-K and quarterly 10-Q reports with the SEC. Pays a quarterly dividend and runs an ongoing share-repurchase program. " +
      "Significant AI investment including a large strategic stake in OpenAI and Copilot products across its portfolio. " +
      "Completed the acquisition of Activision Blizzard. Large, diversified, profitable enterprise software and cloud business.",
  },
};

const profile = COMPANIES[TICKER];
if (!profile) {
  console.error(`No sample profile defined for ${TICKER}. Add one to COMPANIES in this script.`);
  process.exit(1);
}

const disclosure =
  `SAMPLE BRIEF. This is an illustrative example of a PubcoZone Sponsored Research Brief, prepared from public information about ` +
  `${profile.name} ($${profile.ticker}) to demonstrate the format and depth of the product. ${profile.name} did NOT commission or pay for this brief. ` +
  `A real Sponsored Research Brief is commissioned and paid for by the subject company and prepared by PubcoZone from that company's public SEC filings. ` +
  `It is a company-sponsored profile, not independent research or a rating, and it is not investment advice or a recommendation to buy or sell any security. ` +
  `Verify all figures against the company's filings at sec.gov.`;

async function claude(system, user, maxTokens = 4000) {
  if (!ANTHROPIC_KEY) return null;
  // Light retry — section generation is long; tolerate a transient 429/529.
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch("https://api.anthropic.com/v1/messages", {
        method: "POST",
        headers: {
          "x-api-key": ANTHROPIC_KEY,
          "anthropic-version": "2023-06-01",
          "content-type": "application/json",
        },
        body: JSON.stringify({
          model: MODEL,
          max_tokens: maxTokens,
          system,
          messages: [{ role: "user", content: user }],
        }),
      });
      if (res.ok) {
        const j = await res.json();
        return j?.content?.[0]?.text ?? null;
      }
      if (res.status === 429 || res.status >= 500) {
        await new Promise((r) => setTimeout(r, 2000 * (attempt + 1)));
        continue;
      }
      console.error(`Anthropic ${res.status}: ${(await res.text()).slice(0, 200)}`);
      return null;
    } catch (e) {
      console.error(`Anthropic call failed (attempt ${attempt + 1}):`, e.message);
      await new Promise((r) => setTimeout(r, 1500));
    }
  }
  return null;
}

// The report's sections. Each is generated by its own focused Claude call so the
// result is long and genuinely detailed (a single call tends to compress). Order
// here is the order in the final document + the table of contents.
const SECTIONS = [
  { h: "Executive Summary", words: 350, ask: "Open the report with a crisp executive summary: who the company is, what it does, why it matters in its industry, and the 4-6 things a reader most needs to understand. End with a short 'what to watch' line. No recommendation, no price view." },
  { h: "Company Overview & History", words: 600, ask: "Tell the company's story: founding, key milestones and turning points, leadership eras, major pivots and strategic bets, and how it became what it is today. Be specific about widely-known historical facts." },
  { h: "Business Model & How It Makes Money", words: 700, ask: "Explain the business model in depth: the products/services, the customer types, the revenue model (subscriptions, licenses, usage, hardware, ads, etc.), pricing dynamics, switching costs, distribution, and what structurally drives revenue and margin. Explain the economics clearly." },
  { h: "Segment Deep-Dive", words: 800, ask: "Go segment by segment (use the company's real reportable segments). For each: what's in it, the key products, how it earns, its competitive position, and its role in the overall story. Use a markdown table summarizing the segments." },
  { h: "Financial Analysis", words: 800, ask: "Analyze the financial profile qualitatively: revenue mix and durability, gross and operating margin structure, profitability and cash generation, balance-sheet strength, capital allocation (dividends, buybacks, M&A, capex), and what the numbers say about the business quality. Point to EDGAR for exact current figures rather than inventing precise numbers; you may reference well-known approximate scale (e.g. 'tens of billions in annual revenue') where it's safe and clearly general." },
  { h: "Competitive Landscape & Moat", words: 700, ask: "Map the competitive landscape: the main competitors per business line, where the company leads vs. trails, the sources and durability of its moat (network effects, switching costs, scale, ecosystem, IP, brand), and where the moat is most and least defensible. Use a comparison table of the company vs. key rivals." },
  { h: "The Bull Perspective", words: 550, ask: "Present the strongest fair BULL case — grounded in real fundamentals and public facts, not hype. What could go right, what structural advantages compound, what the optimists emphasize. Be persuasive but honest. No price targets or predictions." },
  { h: "The Bear Perspective", words: 550, ask: "Present the strongest fair BEAR case — the real risks, vulnerabilities, things skeptics rightly worry about, and where the company could disappoint. Be candid and specific, even if unflattering. No price targets or predictions." },
  { h: "Market Sentiment & Investor Perception", words: 550, ask: "Describe how the market, analysts, employees, and customers generally perceive the company: reputation, sentiment themes (positive and negative), common debates among investors, and how perception has shifted over time. Frame as general, well-known sentiment, not a live data feed." },
  { h: "Track Record: Successes", words: 550, ask: "Catalog the company's clearest successes and wins: products that worked, strategic bets that paid off, markets it conquered, and execution it got right. Be concrete with widely-known examples." },
  { h: "Track Record: Failures & Missteps", words: 550, ask: "Be honest about the company's failures, flops, missed opportunities, controversies, and strategic mistakes. A credible brief does not hide these. Use concrete, widely-known examples and what was learned." },
  { h: "Risk Factors", words: 650, ask: "A thorough risk section like a 10-K's: competitive, technological/disruption, regulatory/antitrust, concentration, execution and integration (M&A), talent, macro/cyclical, security/operational, and any company-specific risks. Group with bold sub-labels." },
  { h: "Catalysts & What to Watch", words: 550, ask: "Lay out the forward catalysts and watch-items (without predicting outcomes): product cycles, platform shifts, capital-return programs, regulatory decisions, key metrics and filings to monitor. Frame as 'things to watch', explicitly not forecasts." },
  { h: "Governance & Capital Allocation", words: 500, ask: "Cover governance and capital stewardship: board/management approach, how the company allocates capital (dividends, buybacks, M&A, R&D, capex), shareholder-return philosophy, and any well-known governance considerations." },
  { h: "Conclusion", words: 350, ask: "Close with a balanced synthesis: the core of the bull and bear cases side by side, what kind of company this is, and the key open questions — explicitly NOT a recommendation. Remind the reader to verify everything against SEC filings." },
];

const COMPLIANCE = `STRICT COMPLIANCE RULES (this is paid, disclosed content the subject company publishes): ` +
  `NO price targets, NO valuation calls ('undervalued'/'overvalued'/'cheap'), NO buy/sell/hold language, NO predictions, forecasts, or guidance, NO promises about future stock performance. ` +
  `Be accurate, balanced, and grounded ONLY in widely-known public facts and the context provided. For specific current figures, tell the reader to verify on EDGAR rather than inventing precise numbers. Write in clean markdown (use ### sub-headings, **bold** labels, bullet lists, and markdown tables where useful). Do NOT restate the section heading — start with the content. Write thorough, detailed, professional prose.`;

async function generateSection(s, i) {
  const sys = `You are a senior equity research writer producing one section of a long, detailed COMPANY-SPONSORED research brief about a public company. ${COMPLIANCE}`;
  const user =
    `Company context: ${profile.facts}\n\n` +
    `Write the "${s.h}" section. Target roughly ${s.words} words — be substantive and specific. ${s.ask}\n\n` +
    `Output ONLY the section body in markdown (no '## ${s.h}' heading line — that is added for you).`;
  const out = await claude(sys, user, 3000);
  console.log(`  [${i + 1}/${SECTIONS.length}] ${s.h} — ${out ? out.length + " chars" : "FAILED (fallback)"}`);
  const body = out && out.trim()
    ? out.trim()
    : `Detailed analysis for this section is being prepared. Review ${profile.name}'s latest SEC filings on EDGAR (sec.gov) for current specifics.`;
  return `## ${s.h}\n\n${body}`;
}

async function generate() {
  const title = `${profile.name} ($${profile.ticker}) — Sponsored Research Brief`;
  const parts = [];
  // Sequential (not parallel) to stay well under Anthropic rate limits.
  for (let i = 0; i < SECTIONS.length; i++) {
    parts.push(await generateSection(SECTIONS[i], i));
  }
  const toc =
    `> **Sample institutional-style research brief.** Sections below: ` +
    SECTIONS.map((s) => s.h).join(" · ") + ".\n";
  const markdown = `${toc}\n${parts.join("\n\n")}`;
  return { title, markdown };
}

const supabase = createClient(URL, SERVICE_KEY, { auth: { persistSession: false } });

console.log(`Generating sample brief for $${TICKER}…`);
const brief = await generate();

// Remove any existing sample for this ticker so re-runs replace cleanly.
const { error: delErr } = await supabase
  .from("sponsored_briefs")
  .delete()
  .eq("ticker", TICKER)
  .eq("is_sample", true);
if (delErr) {
  console.error("Cleanup of prior sample failed:", delErr.message);
  process.exit(1);
}

const { data, error } = await supabase
  .from("sponsored_briefs")
  .insert({
    company_id: null,
    ticker: TICKER,
    title: brief.title,
    markdown: brief.markdown,
    disclosure,
    status: "published",
    published: true,
    is_sample: true,
  })
  .select("id")
  .single();

if (error) {
  console.error("Insert failed:", error.message);
  process.exit(1);
}

console.log(`✓ Sample brief published for $${TICKER}`);
console.log(`  id:    ${data.id}`);
console.log(`  title: ${brief.title}`);
console.log(`  view:  /briefs/sample  and  /t/${TICKER}`);
